document.addEventListener('DOMContentLoaded', () => {

    const selectionForm = document.getElementById('selection-form');
    const slideContainer = document.getElementById('slide-container');

    // ==========================================
    // LOGIC FOR INDEX.HTML (THE PORTAL)
    // ==========================================
    if (selectionForm) {
        const classSel = document.getElementById('class-select');
        const subjectSel = document.getElementById('subject-select');
        const chapterSel = document.getElementById('chapter-select');
        const periodSel = document.getElementById('period-select');
        const startBtn = document.getElementById('start-btn');

        let catalogData = {};

        // 1. Fetch the catalog
        fetch('data/catalog.json')
            .then(res => res.json())
            .then(data => {
                catalogData = data.classes;
                populateSelect(classSel, Object.keys(catalogData), "Select Class");
            })
            .catch(err => {
                console.error("Error loading catalog:", err);
                classSel.innerHTML = `<option value="">Error loading data!</option>`;
            });

        // 2. Handle Class Selection
        classSel.addEventListener('change', (e) => {
            const cls = e.target.value;
            resetSelects([subjectSel, chapterSel, periodSel]);
            startBtn.disabled = true;
            
            if (cls && catalogData[cls]) {
                const subjects = Object.keys(catalogData[cls].subjects);
                populateSelect(subjectSel, subjects, "Select Subject");
            }
        });

        // 3. Handle Subject Selection
        subjectSel.addEventListener('change', (e) => {
            const cls = classSel.value;
            const sub = e.target.value;
            resetSelects([chapterSel, periodSel]);
            startBtn.disabled = true;

            if (sub && catalogData[cls].subjects[sub]) {
                const chapters = catalogData[cls].subjects[sub].chapters.map(ch => ch.folder_name);
                populateSelect(chapterSel, chapters, "Select Chapter");
            }
        });

        // 4. Handle Chapter Selection
        chapterSel.addEventListener('change', (e) => {
            const cls = classSel.value;
            const sub = subjectSel.value;
            const chName = e.target.value;
            resetSelects([periodSel]);
            startBtn.disabled = true;

            if (chName) {
                const chapterObj = catalogData[cls].subjects[sub].chapters.find(c => c.folder_name === chName);
                if (chapterObj) {
                    populateSelect(periodSel, chapterObj.periods, "Select Period");
                }
            }
        });

        // 5. Handle Period Selection
        periodSel.addEventListener('change', (e) => {
            startBtn.disabled = !e.target.value;
        });

        // 6. Start Class (Redirect to viewer)
        selectionForm.addEventListener('submit', (e) => {
            e.preventDefault();
            const url = `viewer.html?cls=${classSel.value}&sub=${subjectSel.value}&ch=${chapterSel.value}&per=${periodSel.value}`;
            window.location.href = url;
        });

        // Helper Functions
        function populateSelect(element, items, defaultText) {
            element.innerHTML = `<option value="">${defaultText}</option>`;
            items.forEach(item => {
                element.innerHTML += `<option value="${item}">${item}</option>`;
            });
            element.disabled = false;
        }

        function resetSelects(elements) {
            elements.forEach(el => {
                el.innerHTML = `<option value="">Select previous option first</option>`;
                el.disabled = true;
            });
        }
    }

    // ==========================================
    // LOGIC FOR VIEWER.HTML (THE PRESENTATION)
    // ==========================================
    if (slideContainer) {
        const urlParams = new URLSearchParams(window.location.search);
        const cls = urlParams.get('cls');
        const sub = urlParams.get('sub');
        const ch = urlParams.get('ch');
        const per = urlParams.get('per');

        if (!cls || !sub || !ch || !per) {
            slideContainer.innerHTML = `<section><h2>Error</h2><p>Invalid URL parameters. Please go back to the portal.</p></section>`;
            return;
        }

        const dataUrl = `data/${cls}/${sub}/${ch}/${per}`;

        // Fetch the specific period JSON generated by our Python backend
        fetch(dataUrl)
            .then(res => res.json())
            .then(data => {
                slideContainer.innerHTML = ''; // Clear loading text

                // Title Slide
                slideContainer.innerHTML += `
                    <section>
                        <h2>${data.chapter_name}</h2>
                        <p class="text-gray-500">Period ${data.period_no} of ${data.total_periods}</p>
                        <hr>
                        <p style="font-size: 0.7em;">Objective: ${data.learning_objective}</p>
                    </section>
                `;

                // Loop through slides
                data.slides.forEach(slide => {
                    let slideContent = `<section class="slide-${slide.type}">`;
                    slideContent += `<h2>${slide.heading}</h2>`;
                    
                    if (slide.image_url) {
                        slideContent += `<img src="data/${cls}/${sub}/${ch}/${slide.image_url}" alt="Slide Image" style="max-height: 300px;">`;
                    }

                    if (slide.bullets && slide.bullets.length > 0) {
                        slideContent += `<ul>`;
                        slide.bullets.forEach(b => slideContent += `<li>${b}</li>`);
                        slideContent += `</ul>`;
                    }

                    if (slide.content) {
                        slideContent += `<div style="font-size: 0.9em; margin-top: 20px;">${slide.content}</div>`;
                    }
                    
                    if (slide.questions && slide.questions.length > 0) {
                        slideContent += `<div class="homework-box"><ul>`;
                        slide.questions.forEach(q => slideContent += `<li>${q}</li>`);
                        slideContent += `</ul></div>`;
                    }

                    if (slide.teacher_tip) {
                        slideContent += `<div class="teacher-tip">💡 <strong>Teacher Tip:</strong> ${slide.teacher_tip}</div>`;
                    }

                    slideContent += `</section>`;
                    slideContainer.innerHTML += slideContent;
                });

                // Initialize Reveal.js with Math Plugin (KaTeX)
                Reveal.initialize({
                    controls: true,
                    progress: true,
                    center: true,
                    hash: true,
                    transition: 'slide',
                    plugins: [ RevealMath.kaTeX ]
                });
            })
            .catch(err => {
                console.error(err);
                slideContainer.innerHTML = `<section><h2>Error</h2><p>Could not load the slide data. Ensure the JSON file exists.</p></section>`;
            });
    }
});